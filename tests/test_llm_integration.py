import sys
import types

import pandas as pd

from src.feedback_prd import llm


FALLBACK_MARKDOWN = "# PRD: Template fallback\n\nTemplate generated content."


def _sample_need() -> dict[str, object]:
    return {
        "need_summary": "Improve export reliability",
        "category": "Bug",
        "module": "Export",
        "severity": "High",
        "feedback_count": 2,
        "priority_score": 8.5,
    }


def _sample_feedback() -> pd.DataFrame:
    return pd.DataFrame(
        {
            "feedback_text": [
                "Export sometimes fails after selecting Markdown.",
                "The generated report is blank after download.",
            ],
        }
    )


def _generate() -> dict[str, object]:
    return llm.generate_prd_with_llm_metadata(
        _sample_need(),
        _sample_feedback(),
        fallback_markdown=FALLBACK_MARKDOWN,
    )


def test_missing_key_returns_template_fallback_metadata(monkeypatch):
    monkeypatch.setattr(llm, "load_llm_env", lambda: None)
    monkeypatch.delenv("LLM_API_KEY", raising=False)
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.setitem(sys.modules, "openai", None)

    result = _generate()

    assert result["used_llm"] is False
    assert result["status"] == "missing_key"
    assert result["markdown"] == FALLBACK_MARKDOWN
    assert "LLM_API_KEY" in result["message"] or "OPENAI_API_KEY" in result["message"]


def test_configured_key_without_openai_sdk_reports_missing_sdk(monkeypatch):
    monkeypatch.setattr(llm, "load_llm_env", lambda: None)
    monkeypatch.setenv("LLM_API_KEY", "sk-test-not-real")
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.setitem(sys.modules, "openai", None)

    result = _generate()

    assert result["used_llm"] is False
    assert result["markdown"] == FALLBACK_MARKDOWN
    assert result["status"] == "missing_sdk" or (
        "sdk" in str(result["status"]).lower()
        and any(term in str(result["status"]).lower() for term in ("missing", "unavailable"))
    )


def test_fake_openai_success_returns_model_markdown(monkeypatch):
    calls = []
    clients = []
    model_markdown = "## Model PRD\n\nGenerated by the fake model."

    class FakeCompletions:
        def create(self, **kwargs):
            calls.append(kwargs)
            return types.SimpleNamespace(
                choices=[
                    types.SimpleNamespace(
                        message=types.SimpleNamespace(content=model_markdown),
                    )
                ]
            )

    class FakeOpenAI:
        def __init__(self, **kwargs):
            clients.append(kwargs)
            self.chat = types.SimpleNamespace(completions=FakeCompletions())

    fake_openai = types.ModuleType("openai")
    fake_openai.OpenAI = FakeOpenAI

    monkeypatch.setattr(llm, "load_llm_env", lambda: None)
    monkeypatch.setenv("LLM_API_KEY", "sk-fake-success")
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.setitem(sys.modules, "openai", fake_openai)

    result = llm.generate_prd_with_llm_metadata(
        _sample_need(),
        _sample_feedback(),
        fallback_markdown=FALLBACK_MARKDOWN,
        model="fake-model",
    )

    assert result["used_llm"] is True
    assert result["status"] == "llm_success"
    assert result["markdown"] == model_markdown
    assert clients == [{"api_key": "sk-fake-success"}]
    assert calls[0]["model"] == "fake-model"


def test_fake_openai_error_falls_back_without_leaking_key(monkeypatch):
    fake_key = "sk-fake-secret-123"

    class FakeCompletions:
        def create(self, **kwargs):
            raise RuntimeError(f"provider rejected key {fake_key}")

    class FakeOpenAI:
        def __init__(self, **kwargs):
            self.chat = types.SimpleNamespace(completions=FakeCompletions())

    fake_openai = types.ModuleType("openai")
    fake_openai.OpenAI = FakeOpenAI

    monkeypatch.setattr(llm, "load_llm_env", lambda: None)
    monkeypatch.setenv("LLM_API_KEY", fake_key)
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.setitem(sys.modules, "openai", fake_openai)

    result = _generate()

    assert result["used_llm"] is False
    assert result["status"] == "api_error"
    assert result["markdown"] == FALLBACK_MARKDOWN
    assert fake_key not in result["message"]
    assert fake_key not in str(result)
